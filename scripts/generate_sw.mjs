/**
 * Generates an offline-first Service Worker (build/web/sw.js) that precaches
 * every runtime asset produced by `flutter build web --no-web-resources-cdn`.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const BUILD_DIR = path.resolve(process.cwd(), 'build/web');
const SW_PATH = path.join(BUILD_DIR, 'sw.js');
const DEPRECATED_FLUTTER_SW = path.join(BUILD_DIR, 'flutter_service_worker.js');
const EXCLUDED_PATHS = new Set([
  '/sw.js',
  '/vercel.json',
  '/flutter_service_worker.js',
]);

function collectFiles(dir, rootDir) {
  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    // Skip dotfiles (e.g. .last_build_id) because static hosts like Vercel may 404 them.
    if (entry.name.startsWith('.')) continue;

    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...collectFiles(fullPath, rootDir));
    } else if (entry.isFile()) {
      if (entry.name.endsWith('.symbols')) continue;
      const rel = '/' + path.relative(rootDir, fullPath).split(path.sep).join('/');
      if (!EXCLUDED_PATHS.has(rel)) {
        results.push({ url: rel, fullPath });
      }
    }
  }
  return results;
}

if (!fs.existsSync(BUILD_DIR)) {
  console.error(`Missing build directory: ${BUILD_DIR}`);
  process.exit(1);
}

if (fs.existsSync(DEPRECATED_FLUTTER_SW)) {
  fs.rmSync(DEPRECATED_FLUTTER_SW);
}

const files = collectFiles(BUILD_DIR, BUILD_DIR).sort((a, b) =>
  a.url.localeCompare(b.url)
);

const hash = crypto.createHash('sha256');
for (const file of files) {
  hash.update(file.url);
  hash.update(fs.readFileSync(file.fullPath));
}
const cacheName = `quick-fdr-${hash.digest('hex').slice(0, 12)}`;
const precacheUrls = files.map((f) => f.url);

const swSource = `// Auto-generated by scripts/generate_sw.mjs. Do not edit by hand.
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_URLS))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys
          .filter((key) => key.startsWith('quick-fdr-') && key !== CACHE_NAME)
          .map((key) => caches.delete(key))
      )
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;

  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;

  if (event.request.mode === 'navigate' || url.pathname === '/') {
    event.respondWith(
      caches.match('/index.html', { ignoreSearch: true }).then(
        (cached) => cached || fetch(event.request)
      )
    );
    return;
  }

  event.respondWith(
    caches.match(event.request, { ignoreSearch: true }).then(
      (cached) => cached || fetch(event.request)
    )
  );
});
`;

fs.writeFileSync(SW_PATH, swSource, 'utf8');
console.log(`Generated ${SW_PATH} (${precacheUrls.length} precached files, cache=${cacheName})`);
